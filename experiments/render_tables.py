"""Render markdown result tables from results/*.json, and sync them into README.

The README carries an auto-generated block between AUTO-TABLES markers.
`--write-readme` regenerates it; `--check-readme` fails (exit 1) if the README
does not match the results JSONs — the guarantee that every published number
comes from an actual run.
"""

from __future__ import annotations

import argparse
import re
import sys

from experiments.common import load_results
from quantum_credit import config

BEGIN = "<!-- AUTO-TABLES:BEGIN (generated by experiments/render_tables.py — do not edit) -->"
END = "<!-- AUTO-TABLES:END -->"

LABELS = {
    "logistic_calibrated": "Logistic regression (calibrated)",
    "random_forest": "Random forest",
    "hist_gradient_boosting": "Gradient boosting (HGB)",
    "svc_rbf": "SVC, RBF kernel (classical twin)",
    "qk_svc_d4": "**QK-SVC, fidelity kernel, d=4**",
    "qk_svc_d8": "**QK-SVC, fidelity kernel, d=8**",
    "vqc_d4": "**VQC, d=4**",
}
ORDER = [
    "logistic_calibrated", "random_forest", "hist_gradient_boosting", "svc_rbf",
    "qk_svc_d4", "qk_svc_d8", "vqc_d4",
]


def table_full(full: dict) -> str:
    lines = [
        "### Part 1 — classical models, full training set (n = "
        f"{full['data']['n_train']:,}; test n = {full['data']['n_test']:,})",
        "",
        "| Model | CV AUC (5-fold) | Test AUC | Test PR-AUC | Test Brier | "
        "Cost @ t*OOF | Profit @ t*OOF (NT$ M) | Fit time (s) |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name in ["logistic_calibrated", "random_forest", "hist_gradient_boosting"]:
        e = full["models"][name]
        cv = e["cv"]["auc"]
        lines.append(
            f"| {LABELS[name]} "
            f"| {cv['mean']:.4f} ± {cv['std']:.4f} "
            f"| {e['test']['auc']:.4f} "
            f"| {e['test']['pr_auc']:.4f} "
            f"| {e['test']['brier']:.4f} "
            f"| {e['test_decisions']['expected_cost_at_oof_threshold']:.4f} "
            f"| {e['test_decisions']['profit_at_oof_threshold_ntd'] / 1e6:.1f} "
            f"| {e['timing_s']['fit']:.1f} |"
        )
    lines += [
        "",
        f"Cost matrix: missed default (FN) = {full['config']['cost_fn']:.0f}, "
        f"rejected good client (FP) = {full['config']['cost_fp']:.0f} "
        f"(Bayes threshold t* = {full['config']['bayes_threshold']:.3f}). "
        "Operating thresholds chosen on out-of-fold training predictions only.",
    ]
    return "\n".join(lines)


def table_matched(matched: dict) -> str:
    sizes = matched["config"]["sizes"]
    agg = matched["aggregates"]
    lines = [
        "### Part 2 — the honest table: identical subsamples, classical vs quantum",
        "",
        f"Test AUC, mean ± std over {len(matched['config']['seeds'])} stratified "
        f"subsample draws; every model trained on the *same* subsamples, evaluated on the "
        f"same fixed test set (n = {matched['config']['n_test']:,}).",
        "",
        "| Model | " + " | ".join(f"n = {s}" for s in sizes) + " | Train+test time @ n=2000 |",
        "|---|" + "---|" * (len(sizes) + 1),
    ]
    for name in ORDER:
        if name not in agg[str(sizes[0])]:
            continue
        cells = []
        for s in sizes:
            a = agg[str(s)][name]["auc"]
            cells.append(f"{a['mean']:.4f} ± {a['std']:.4f}")
        t = agg[str(max(sizes))][name]["total_time_s"]["mean"]
        lines.append(f"| {LABELS[name]} | " + " | ".join(cells) + f" | {t:.1f} s |")
    return "\n".join(lines)


def table_cost_matched(matched: dict) -> str:
    sizes = matched["config"]["sizes"]
    agg = matched["aggregates"]
    t = matched["config"]["bayes_threshold"]
    lines = [
        "### Part 2b — expected cost per applicant at the fixed Bayes threshold "
        f"(t* = {t:.3f}, lower is better)",
        "",
        "| Model | " + " | ".join(f"n = {s}" for s in sizes) + " |",
        "|---|" + "---|" * len(sizes),
    ]
    for name in ORDER:
        if name not in agg[str(sizes[0])]:
            continue
        cells = []
        for s in sizes:
            a = agg[str(s)][name]["cost_at_bayes_threshold"]
            cells.append(f"{a['mean']:.4f} ± {a['std']:.4f}")
        lines.append(f"| {LABELS[name]} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_block() -> str:
    full = load_results("classical_full.json")
    matched = load_results("matched_subsamples.json")
    return "\n\n".join([BEGIN, table_full(full), table_matched(matched),
                        table_cost_matched(matched), END])


def sync_readme(write: bool) -> int:
    readme = config.REPO_ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    block = render_block()
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        print("README has no AUTO-TABLES block")
        return 1
    new_text = pattern.sub(lambda _: block, text)
    if write:
        readme.write_text(new_text, encoding="utf-8")
        print("[synced] README auto-tables")
        return 0
    if new_text != text:
        print("MISMATCH: README tables do not match results/*.json "
              "(run: python experiments/render_tables.py --write-readme)")
        return 1
    print("README tables match results/*.json")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write-readme", action="store_true")
    g.add_argument("--check-readme", action="store_true")
    g.add_argument("--print", dest="print_only", action="store_true")
    args = ap.parse_args()
    if args.print_only:
        print(render_block())
        return 0
    return sync_readme(write=args.write_readme)


if __name__ == "__main__":
    sys.exit(main())
